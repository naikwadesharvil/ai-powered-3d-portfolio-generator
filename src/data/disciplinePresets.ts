/**
 * Returns the matching discipline preset or a customized fallback.
 */
export function getDisciplinePreset(branch?: EducationBranch, customBranchName?: string): DisciplinePreset {
  const selectedBranch = branch || 'cs_it';
  const base = DISCIPLINE_PRESETS[selectedBranch] || DISCIPLINE_PRESETS.custom;

  if (selectedBranch === 'custom' && customBranchName && customBranchName.trim().length > 0) {
    const formatted = customBranchName.trim();
    return {
      ...base,
      label: formatted,
      shortName: formatted.split(' ')[0] || formatted,
      roleHeadlines: {
        student: `${formatted} Student | Emerging Specialist & Project Developer`,
        job_seeker: `${formatted} Professional | Results-Driven Specialist`,
        professional: `Senior ${formatted} Lead | Strategic Specialist`,
        freelancer: `Independent ${formatted} Consultant & Specialist`,
      },
      roleShortBios: {
        student: `Student in ${formatted} dedicated to practical project delivery, continuous learning, and mastering industry methodologies.`,
        job_seeker: `Skilled in ${formatted} with a proven track record of successful execution, technical problem-solving, and attention to quality standards.`,
        professional: `Experienced leader in ${formatted} driving critical initiatives, managing cross-functional teams, and achieving measurable excellence.`,
        freelancer: `Independent consultant in ${formatted} delivering tailored client solutions, strategic guidance, and high-impact deliverables.`,
      },
      telemetryCode: `SYS // ${formatted.toUpperCase().replace(/[^A-Z0-9]/g, '-')}-CORE`,
    };
  }

  return base;
}

